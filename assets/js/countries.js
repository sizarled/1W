const BY_CODE = new Map(COUNTRIES.map((row) => [row.code.toLowerCase(), row]));
const BY_NAME = new Map(COUNTRIES.map((row) => [row.name.toLowerCase(), row]));

/** Flag URL for an ISO code (`ma` → `assets/flags/ma.svg`). */
export function flagSrc(code) {
  const key = String(code || "").toLowerCase();
  return BY_CODE.has(key) ? `assets/flags/${key}.svg` : "";
}

/** The country row of an ISO code, or null. */
export function countryByCode(code) {
  return BY_CODE.get(String(code || "").toLowerCase()) || null;
}

/** The country row of an English name, or null. */
export function countryByName(name) {
  const key = String(name || "").trim().toLowerCase();
  if (!key) return null;
  return BY_NAME.get(key) || COUNTRIES.find((row) => row.name.toLowerCase().startsWith(key)) || null;
}

/** `<img>` markup for a flag — empty when the code is unknown. */
export function flagMarkup(code, { size = 20, label = "" } = {}) {
  const src = flagSrc(code);
  if (!src) return "";
  const alt = label ? ` alt="${label}"` : ' alt="" aria-hidden="true"';
  return `<img class="flag" src="${src}" width="${size}" height="${Math.round((size * 3) / 4)}" loading="lazy" decoding="async"${alt} />`;
}

/** Case-insensitive search over the names, used by the pickers. */
export function searchCountries(query, limit = 60) {
  const key = String(query || "").trim().toLowerCase();
  if (!key) return COUNTRIES.slice(0, limit);
  return COUNTRIES.filter((row) => row.name.toLowerCase().includes(key) || row.code === key).slice(0, limit);
}
